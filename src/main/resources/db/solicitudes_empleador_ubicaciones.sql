-- =============================================================================
-- US-MAP-08 - Ubicaciones de Google Places en solicitudes de empleador
-- =============================================================================
-- Base PostgreSQL de AppointMee. Ejecutar como un solo bloque (psql -f, Supabase
-- SQL Editor o cualquier cliente). El backend usa spring.jpa.hibernate.ddl-auto=
-- validate: ESTE SCRIPT ES OBLIGATORIO antes de desplegar el backend.
--
-- ORDEN DE EJECUCION (el archivo ya viene en este orden):
--   1. Ampliar solicitudes_empleador.motivo de 300 a 3000 caracteres.
--   2. Crear la tabla de ubicaciones propuestas y sus restricciones.
--   3. Crear/asegurar los indices que usan los listados administrativos.
--   4. Consultas de verificacion (incluidas al final, solo lectura).
--
-- DIFERENCIAS CONTRA UN ESQUEMA ANTIGUO QUE SE CORRIGEN AQUI:
--   - No existe la tabla solicitudes_empleador_ubicaciones.
--   - motivo suele ser VARCHAR(300) (o tener un CHECK de 300): se amplia.
--   - No existe el indice por fecha para el listado sin filtro de estado.
--   - Puede no existir el indice (estado, fecha, id) de optimizacion_consultas.sql.
-- Las solicitudes ya registradas NO se eliminan ni se modifican (salvo un motivo
-- NULL, que no deberia existir, para poder aplicar NOT NULL). Las solicitudes
-- historicas simplemente no tendran filas en la tabla nueva y el backend
-- respondera ubicaciones: [] en su detalle.
--
-- Nota: no se agrega limite al numero de ubicaciones. Cada fila esta acotada por
-- los tipos de columna y por CHECKs; no hay una restriccion arbitraria de count.
-- =============================================================================

BEGIN;

-- -----------------------------------------------------------------------------
-- 1. Comentario / motivo: 300 -> 3000 caracteres
-- -----------------------------------------------------------------------------
ALTER TABLE public.solicitudes_empleador
    ADD COLUMN IF NOT EXISTS motivo VARCHAR(3000);

-- Solo si la columna admitia NULL (esquema anterior incompleto).
DO $motivo$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'solicitudes_empleador'
          AND column_name = 'motivo'
          AND is_nullable = 'YES'
    ) THEN
        UPDATE public.solicitudes_empleador
        SET motivo = ''
        WHERE motivo IS NULL;

        ALTER TABLE public.solicitudes_empleador
            ALTER COLUMN motivo SET NOT NULL;
    END IF;
END
$motivo$;

-- Si algun despliegue anterior puso un CHECK de longitud sobre motivo, se quita
-- para que no quede un limite de 300 que falle al guardar textos mas largos.
DO $checks$
DECLARE
    restriccion RECORD;
BEGIN
    FOR restriccion IN
        SELECT conname
        FROM pg_constraint
        WHERE conrelid = 'public.solicitudes_empleador'::regclass
          AND contype = 'c'
          AND pg_get_constraintdef(oid) ILIKE '%motivo%'
          AND pg_get_constraintdef(oid) ~ '300'
    LOOP
        EXECUTE format(
            'ALTER TABLE public.solicitudes_empleador DROP CONSTRAINT %I',
            restriccion.conname);
    END LOOP;
END
$checks$;

ALTER TABLE public.solicitudes_empleador
    ALTER COLUMN motivo TYPE VARCHAR(3000)
    USING motivo::VARCHAR(3000);

-- -----------------------------------------------------------------------------
-- 2. Ubicaciones propuestas por solicitud
-- -----------------------------------------------------------------------------
-- INTEGER GENERATED BY DEFAULT AS IDENTITY coincide con
-- @GeneratedValue(strategy = IDENTITY) sobre un campo Integer de Java.
-- ON DELETE CASCADE coincide con orphanRemoval/cascade de la entidad.
CREATE TABLE IF NOT EXISTS public.solicitudes_empleador_ubicaciones (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY,
    direccion         VARCHAR(500)      NOT NULL,
    latitud           DOUBLE PRECISION  NOT NULL,
    longitud          DOUBLE PRECISION  NOT NULL,
    google_place_id   VARCHAR(255)      NOT NULL,
    solicitud_id      INTEGER           NOT NULL,

    CONSTRAINT pk_solicitudes_empleador_ubicaciones
        PRIMARY KEY (id),
    CONSTRAINT fk_solicitudes_empleador_ubicaciones_solicitud
        FOREIGN KEY (solicitud_id)
        REFERENCES public.solicitudes_empleador (id)
        ON DELETE CASCADE,
    CONSTRAINT ck_solicitudes_empleador_ubicaciones_direccion
        CHECK (btrim(direccion) <> ''),
    CONSTRAINT ck_solicitudes_empleador_ubicaciones_latitud
        CHECK (latitud >= -90 AND latitud <= 90),
    CONSTRAINT ck_solicitudes_empleador_ubicaciones_longitud
        CHECK (longitud >= -180 AND longitud <= 180),
    CONSTRAINT ck_solicitudes_empleador_ubicaciones_place_id
        CHECK (btrim(google_place_id) <> '')
);

-- Asegura el tipo exacto del mapping si la tabla ya existia con otra definicion.
-- Si hay filas con NULL, ALTER ... SET NOT NULL falla a proposito: no se borra
-- ni se inventa informacion de ubicaciones historicas.
ALTER TABLE public.solicitudes_empleador_ubicaciones
    ALTER COLUMN direccion TYPE VARCHAR(500) USING direccion::VARCHAR(500),
    ALTER COLUMN google_place_id TYPE VARCHAR(255) USING google_place_id::VARCHAR(255),
    ALTER COLUMN latitud TYPE DOUBLE PRECISION USING latitud::DOUBLE PRECISION,
    ALTER COLUMN longitud TYPE DOUBLE PRECISION USING longitud::DOUBLE PRECISION,
    ALTER COLUMN direccion SET NOT NULL,
    ALTER COLUMN google_place_id SET NOT NULL,
    ALTER COLUMN latitud SET NOT NULL,
    ALTER COLUMN longitud SET NOT NULL,
    ALTER COLUMN solicitud_id SET NOT NULL;

-- Restricciones idempotentes (PostgreSQL no tiene ADD CONSTRAINT IF NOT EXISTS).
DO $restricciones$
DECLARE
    existente BOOLEAN;
BEGIN
    SELECT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.solicitudes_empleador_ubicaciones'::regclass
          AND conname = 'fk_solicitudes_empleador_ubicaciones_solicitud'
    ) INTO existente;
    IF NOT existente THEN
        ALTER TABLE public.solicitudes_empleador_ubicaciones
            ADD CONSTRAINT fk_solicitudes_empleador_ubicaciones_solicitud
            FOREIGN KEY (solicitud_id)
            REFERENCES public.solicitudes_empleador (id)
            ON DELETE CASCADE;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.solicitudes_empleador_ubicaciones'::regclass
          AND conname = 'ck_solicitudes_empleador_ubicaciones_direccion'
    ) THEN
        ALTER TABLE public.solicitudes_empleador_ubicaciones
            ADD CONSTRAINT ck_solicitudes_empleador_ubicaciones_direccion
            CHECK (btrim(direccion) <> '');
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.solicitudes_empleador_ubicaciones'::regclass
          AND conname = 'ck_solicitudes_empleador_ubicaciones_latitud'
    ) THEN
        ALTER TABLE public.solicitudes_empleador_ubicaciones
            ADD CONSTRAINT ck_solicitudes_empleador_ubicaciones_latitud
            CHECK (latitud >= -90 AND latitud <= 90);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.solicitudes_empleador_ubicaciones'::regclass
          AND conname = 'ck_solicitudes_empleador_ubicaciones_longitud'
    ) THEN
        ALTER TABLE public.solicitudes_empleador_ubicaciones
            ADD CONSTRAINT ck_solicitudes_empleador_ubicaciones_longitud
            CHECK (longitud >= -180 AND longitud <= 180);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.solicitudes_empleador_ubicaciones'::regclass
          AND conname = 'ck_solicitudes_empleador_ubicaciones_place_id'
    ) THEN
        ALTER TABLE public.solicitudes_empleador_ubicaciones
            ADD CONSTRAINT ck_solicitudes_empleador_ubicaciones_place_id
            CHECK (btrim(google_place_id) <> '');
    END IF;
END
$restricciones$;

-- -----------------------------------------------------------------------------
-- 3. Indices
-- -----------------------------------------------------------------------------
-- (estado, fecha, id): consulta administrativa con ?estado=... y control de
-- solicitud pendiente duplicada por usuario (este ultimo usa ademas el indice
-- idx_solicitudes_empleador_usuario_estado de optimizacion_consultas.sql).
CREATE INDEX IF NOT EXISTS idx_solicitudes_empleador_estado_fecha
    ON public.solicitudes_empleador (estado, fecha_solicitud DESC, id DESC);

-- (fecha, id): NUEVO. Antes solo se listaban pendientes y el indice anterior
-- empezaba por estado; al listar TODOS los estados sin filtro, este indice
-- evita ordenar la tabla completa.
CREATE INDEX IF NOT EXISTS idx_solicitudes_empleador_fecha
    ON public.solicitudes_empleador (fecha_solicitud DESC, id DESC);

CREATE INDEX IF NOT EXISTS idx_solicitudes_empleador_usuario_estado
    ON public.solicitudes_empleador (usuario_id, estado);

-- Recuperacion del detalle: JOIN por solicitud_id.
CREATE INDEX IF NOT EXISTS idx_solicitudes_empleador_ubicaciones_solicitud
    ON public.solicitudes_empleador_ubicaciones (solicitud_id);

COMMIT;

-- -----------------------------------------------------------------------------
-- 4. Verificacion opcional (solo lectura)
-- -----------------------------------------------------------------------------
-- Debe devolver: motivo -> character varying(3000), NOT NULL; tabla de
-- ubicaciones con 8 columnas; FK y 4 CHECKs; 4 indices sobre solicitudes y 1
-- sobre ubicaciones.
SELECT table_name, column_name, data_type, character_maximum_length, is_nullable
FROM information_schema.columns
WHERE table_schema = 'public'
  AND ((table_name = 'solicitudes_empleador' AND column_name = 'motivo')
       OR table_name = 'solicitudes_empleador_ubicaciones')
ORDER BY table_name, ordinal_position;

SELECT conname, contype, pg_get_constraintdef(oid) AS definicion
FROM pg_constraint
WHERE conrelid = 'public.solicitudes_empleador_ubicaciones'::regclass
ORDER BY conname;

SELECT tablename, indexname
FROM pg_indexes
WHERE schemaname = 'public'
  AND tablename IN ('solicitudes_empleador', 'solicitudes_empleador_ubicaciones')
ORDER BY tablename, indexname;
